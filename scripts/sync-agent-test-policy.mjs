#!/usr/bin/env node

/**
 * Copies the CORE rules block out of docs/agents/testing-policy.md into
 * every agent-specific instruction file, delimited by markers that carry a
 * checksum of the source block. `--check` fails when an adapter's block has
 * drifted (hand-edited or stale); `--write` regenerates it in place without
 * touching anything else in the file.
 */

import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { pathToFileURL } from "node:url";
import { REPOSITORY_ROOT } from "./local-env.mjs";

export const POLICY_PATH = path.join(REPOSITORY_ROOT, "docs/agents/testing-policy.md");

/** Adapters actually adopted by this repository. Add one only when the
 * repository actually uses that agent — see testing-policy.md "Relationship
 * to adapters". */
export const ADAPTERS = [
  { path: path.join(REPOSITORY_ROOT, "AGENTS.md") },
  { path: path.join(REPOSITORY_ROOT, "CLAUDE.md") },
];

const CORE_START = "<!-- test-policy:core:start -->";
const CORE_END = "<!-- test-policy:core:end -->";
const BLOCK_START_PATTERN = /<!-- test-policy:start checksum=([a-f0-9]{12}) -->/;
const BLOCK_END = "<!-- test-policy:end -->";

export function extractCoreBlock(policyMarkdown) {
  const startIndex = policyMarkdown.indexOf(CORE_START);
  const endIndex = policyMarkdown.indexOf(CORE_END);
  if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
    throw new Error(`${POLICY_PATH} is missing matching ${CORE_START}/${CORE_END} markers`);
  }
  return policyMarkdown.slice(startIndex + CORE_START.length, endIndex).trim();
}

export function computeChecksum(coreBlockText) {
  return crypto.createHash("sha256").update(coreBlockText, "utf8").digest("hex").slice(0, 12);
}

export function buildGeneratedBlock(coreBlockText, checksum) {
  return [
    `<!-- test-policy:start checksum=${checksum} -->`,
    "## Test ownership policy (generated — do not hand-edit)",
    "",
    "Generated by `scripts/sync-agent-test-policy.mjs` from",
    "`docs/agents/testing-policy.md`. Read the full policy there before adding",
    "or materially changing a test; this block is a summary, not the source.",
    "",
    coreBlockText,
    "",
    BLOCK_END,
  ].join("\n");
}

function findExistingBlock(content) {
  const startMatch = content.match(BLOCK_START_PATTERN);
  if (!startMatch) return null;
  const startIndex = startMatch.index;
  const endIndex = content.indexOf(BLOCK_END, startIndex);
  if (endIndex === -1) return null;
  return {
    checksum: startMatch[1],
    startIndex,
    endIndex: endIndex + BLOCK_END.length,
    text: content.slice(startIndex, endIndex + BLOCK_END.length),
  };
}

/** Insert after the file's first top-level heading when no block exists yet. */
function insertAfterFirstHeading(content, generatedBlock) {
  const headingMatch = content.match(/^# .*$/m);
  if (!headingMatch) {
    return `${generatedBlock}\n\n${content}`;
  }
  const insertAt = headingMatch.index + headingMatch[0].length;
  return `${content.slice(0, insertAt)}\n\n${generatedBlock}\n${content.slice(insertAt)}`;
}

export function syncAdapterContent(existingContent, generatedBlock) {
  const existingBlock = findExistingBlock(existingContent);
  if (!existingBlock) {
    return insertAfterFirstHeading(existingContent, generatedBlock);
  }
  return (
    existingContent.slice(0, existingBlock.startIndex) +
    generatedBlock +
    existingContent.slice(existingBlock.endIndex)
  );
}

export function checkAdapterContent(existingContent, generatedBlock) {
  const existingBlock = findExistingBlock(existingContent);
  if (!existingBlock) {
    return { ok: false, reason: "no generated test-policy block found" };
  }
  if (existingBlock.text !== generatedBlock) {
    return { ok: false, reason: "generated test-policy block has drifted from the canonical source" };
  }
  return { ok: true };
}

function loadGeneratedBlock() {
  const policyMarkdown = fs.readFileSync(POLICY_PATH, "utf8");
  const coreBlockText = extractCoreBlock(policyMarkdown);
  const checksum = computeChecksum(coreBlockText);
  return buildGeneratedBlock(coreBlockText, checksum);
}

function runCli() {
  const mode = process.argv[2];
  if (mode !== "--check" && mode !== "--write") {
    console.error("Usage: sync-agent-test-policy.mjs --check|--write");
    process.exitCode = 2;
    return;
  }

  const generatedBlock = loadGeneratedBlock();
  const failures = [];

  for (const adapter of ADAPTERS) {
    const exists = fs.existsSync(adapter.path);
    const existingContent = exists ? fs.readFileSync(adapter.path, "utf8") : "";
    const relativePath = path.relative(REPOSITORY_ROOT, adapter.path);

    if (mode === "--check") {
      const result = checkAdapterContent(existingContent, generatedBlock);
      if (!result.ok) {
        failures.push(`${relativePath}: ${result.reason}`);
      }
      continue;
    }

    const nextContent = syncAdapterContent(existingContent, generatedBlock);
    if (nextContent !== existingContent) {
      fs.writeFileSync(adapter.path, nextContent);
      console.log(`Updated ${relativePath}`);
    } else {
      console.log(`${relativePath} already synchronized`);
    }
  }

  if (mode === "--check") {
    if (failures.length > 0) {
      console.error(`Agent test-policy adapters are out of sync (${failures.length}):`);
      for (const failure of failures) {
        console.error(`- ${failure}`);
      }
      console.error("Run `node scripts/sync-agent-test-policy.mjs --write` to regenerate.");
      process.exitCode = 1;
      return;
    }
    console.log(`${ADAPTERS.length} agent test-policy adapter(s) are synchronized.`);
  }
}

if (
  process.argv[1] &&
  pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url
) {
  runCli();
}
